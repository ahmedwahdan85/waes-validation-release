"""Write src/vectors.h: the 784 WAES-256 known-answer vectors of
golden/gen_vectors.py and a counter-mode keystream from golden/rijndael_ref.py."""
import os
import sys
import tempfile

root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
gold = os.path.join(root, '..', '..', 'reference')
sys.path.insert(0, gold)
import gen_vectors  # noqa: E402
from rijndael_ref import ctr_keystream  # noqa: E402

tmp = os.path.join(tempfile.mkdtemp(), 'v.txt')
gen_vectors.main(tmp)
keys, pt, ct, kidx = [], [], [], []
for line in open(tmp):
    f = line.split()
    if f[0] == 'K':
        keys.append(bytes.fromhex(f[1]))
    else:
        pt.append(bytes.fromhex(f[1]))
        ct.append(bytes.fromhex(f[2]))
        kidx.append(len(keys) - 1)

KS_KEY = bytes.fromhex('603deb1015ca71be2b73aef0857d77811f352c073b6108d72d9810a30914dff4')
KS_NONCE = bytes(range(0xa0, 0xb0))
KS_N = 37
ks = list(ctr_keystream(KS_KEY, KS_NONCE, KS_N))


def arr(b):
    return '{' + ','.join(f'0x{x:02x}' for x in b) + '}'


with open(os.path.join(root, 'src', 'vectors.h'), 'w') as o:
    o.write('/* Generated by scripts/gen_vectors_h.py from golden/gen_vectors.py and golden/rijndael_ref.py */\n')
    o.write('#include <stdint.h>\n')
    o.write(f'#define N_KEYS {len(keys)}\n#define N_VEC {len(pt)}\n#define KS_N {KS_N}\n')
    o.write('static const uint8_t vec_key[N_KEYS][32] = {\n' + ',\n'.join(arr(k) for k in keys) + '};\n')
    o.write('static const uint8_t vec_kidx[N_VEC] = {' + ','.join(map(str, kidx)) + '};\n')
    o.write('static const uint8_t vec_pt[N_VEC][32] = {\n' + ',\n'.join(arr(p) for p in pt) + '};\n')
    o.write('static const uint8_t vec_ct[N_VEC][32] = {\n' + ',\n'.join(arr(c) for c in ct) + '};\n')
    o.write(f'static const uint8_t ks_key[32] = {arr(KS_KEY)};\n')
    o.write(f'static const uint8_t ks_nonce[16] = {arr(KS_NONCE)};\n')
    o.write('static const uint8_t ks_ref[KS_N][32] = {\n' + ',\n'.join(arr(k) for k in ks) + '};\n')
print(f'{len(pt)} vectors, {len(keys)} keys, {KS_N} keystream blocks')
